import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const projectRoot = path.resolve(import.meta.dirname, "..");
// Invoke the CLI's Node entry point with the current interpreter rather than the
// `node_modules/.bin` shim: Node refuses to spawn `.cmd` files without a shell.
const cliEntry = path.join(projectRoot, "node_modules", "supabase", "dist", "supabase.js");

if (!existsSync(cliEntry)) {
  console.error("Supabase CLI is not installed. Run `pnpm install --frozen-lockfile` first.");
  process.exit(1);
}

const stdout = execFileSync(process.execPath, [cliEntry, "status", "--output", "json"], {
  cwd: projectRoot,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});

// The CLI prints a "Stopped services:" notice before the JSON payload.
const status = JSON.parse(stdout.slice(stdout.indexOf("{")));

const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY;

if (!apiUrl || !anonKey) {
  console.error("Local Supabase status did not expose an API URL and anon key.");
  process.exit(1);
}

const host = new URL(apiUrl).hostname;
const isLocal = host === "127.0.0.1" || host === "localhost" || host === "::1";
if (!isLocal && process.env.SUPABASE_ENV_ALLOW_REMOTE !== "1") {
  console.error(`Refusing to write ${apiUrl}: it is not a loopback local stack URL.`);
  console.error("Set SUPABASE_ENV_ALLOW_REMOTE=1 only if you deliberately target a hosted project.");
  process.exit(1);
}

const target = path.join(projectRoot, ".env.local");
writeFileSync(
  target,
  "# Generated by scripts/local-supabase-env.mjs from the local Supabase stack. Do not commit.\n" +
    `VITE_SUPABASE_URL=${apiUrl}\n` +
    `VITE_SUPABASE_ANON_KEY=${anonKey}\n`,
  "utf8",
);

console.log(`Wrote browser-safe local config to ${path.relative(process.cwd(), target)}`);
console.log(`  VITE_SUPABASE_URL=${apiUrl}`);
console.log("  VITE_SUPABASE_ANON_KEY=<local anon key, from supabase status>");
